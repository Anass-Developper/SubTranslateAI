const translations: Record<UiLanguage, Record<TranslationKey, string>> = {
  fr: french,
  en: english,
};

export function resolveUiLanguage(
  preference: InterfaceLocale,
  detectedLanguage: string | undefined,
): UiLanguage {
  if (preference === "fr" || preference === "en") {
    return preference;
  }
  return detectedLanguage?.trim().toLowerCase().replaceAll("_", "-").startsWith("fr") ? "fr" : "en";
}

export function translate(language: UiLanguage, key: TranslationKey): string {
  return translations[language][key];
}
